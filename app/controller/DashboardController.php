    /**
     * Dashboard request handler
     */
    public function dashboard(){
        if(empty($this->userObject)){
            $user = new User($this->currentUserId);
            $this->userObject = $user;
        }

        $this->dataForView['currentUri'] = 'dashboard';

        $viewToRender = 'dashboard/my_dashboard';


        // Todo: Check if user is a regular employee or not
        if($this->userObject->position === User::NISSAN_SUPER){
            // Nissan admin user login
            $viewToRender = 'dashboard/nissan_super_dashboard';
            $regions = $this->userObject->getManagedRegions();
            $this->dataForView['regions'] = $regions;
            $this->_prepareDashboardDataForNissanSuper();
        }elseif($this->userObject->isDealersOwner()){
            // Load dealers' owner view
            $viewToRender = 'dashboard/dealer_owner_dashboard';
        }elseif ($this->userObject->isRegionsManager()){
            // Load regions' sales manager view
            $viewToRender = 'dashboard/region_sales_manger_dashboard';
            $regions = $this->userObject->getManagedRegions();
            $this->dataForView['regions'] = $regions;
            //
            $this->_prepareDashboardDataForDSM();
        }else{
            // Load regular employee's view
            /**
             * @var IRole $role
             */
            $role = null;

            $role = RoleFactory::GetRole($this->userObject->position, $this->userObject);

            if(is_null($role)){
                echo 'No matched role and view found';
                return;
            }
            /**
             * Inject All necessary data to the view
             */
            $this->fetchDashboardData();
            $this->_prepareDashboardData($role);
        }
        // Render the view

        $this->render($viewToRender);
        return;
    }

    /**
     * Someone's lifetime revenue page
     */
    public function lifetime(){
        if(empty($this->userObject)){
            $user = new User($this->currentUserId);
            $this->userObject = $user;
        }
        $this->dataForView['currentUri'] = 'dashboard';

        /**
         * Get Data
         */
        $data = DataSource::Query($this->userObject);
        $results = $data['result']['Results'];

        $lifetime   = 0;
        $monthly    = [];
        $carbon = Carbon::create(env('YEAR'),3,1);
        foreach (range(0,11) as $i) {
            $index = $carbon->addMonth()->format('M-Y');
            if(isset($results[$index])){
                $lifetime = (isset($results[$index]['lifetime']) ? $results[$index]['lifetime'] : $results[$index]['credit_mtd']);
                $monthly[] = [$index, $results[$index]['credit_mtd']];
            }else{
                $monthly[] = [$index, 0];
            }
        }
        $lifetimeUtil = LifetimeUtil::GetInstance($lifetime);

        $historyRows = History::GetLifetime($this->userObject);
        $history = [];

        $now = Carbon::now();
        if( $now->month <= 3 || env('YEAR')== date('Y')-1 ){
            $currentYearData = array_shift($historyRows);
            $historyRows[0] = $currentYearData;
            $historyRows[0][0] = ($now->year -1).'' ;
        }

        /**
         * Need to handle the Fast Finish credits
         */
        foreach ($historyRows as $historyRow) {
            $subTotal = floatval($historyRow[1]);
            if($historyRow[3] > 0){
                // Has FF
                $subTotal += $historyRow[3];
            }
            if($subTotal > 0){
                $history[] = [
                    $historyRow[0],
                    $subTotal
                ] ;
            }


        }

        $this->dataForView['dashboard'] = [
            'lifeTime'=>$lifetime,
            'lifetimeUtil'=>[
                'level_color'=>$lifetimeUtil->color,
                'next_level'=>$lifetimeUtil->next_level,
                'lifetime_to_reach_credits'=>$lifetimeUtil->lifetime_to_reach_credits,
            ],
            'gaga_data' =>$lifetimeUtil->getGagaData(),
            'max'       =>LifetimeUtil::Platinum,
            'monthly'   =>$monthly,
            'history'   =>$history
        ];

        $this->dataForView['extra_js'] = [
            'https://www.gstatic.com/charts/loader.js',
            'https://www.google.com/jsapi',
            asset('js/justgage/raphael-2.1.4.min.js'),
            asset('js/justgage/justgage.js'),
            asset('js/dashboard/lifetime.js')
        ];

        $this->render('dashboard/lifetime');
        return;
    }

    /**
     * Load user's metrics data from data base
