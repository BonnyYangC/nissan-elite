        $this->metricsData = $data['result']['Results'];
    }

    /**
     * Fetch data for dashboard view and inject
     */
    protected function fetchDashboardData(){
        $this->dataForView['Results']       = [];
        $this->dataForView['Excellence']    = 0;
        $this->dataForView['History']       = null;
        $this->dataForView['Credits']       = null;

        $result = DataSource::Query($this->userObject);
        $this->dataForView['Results'] = $result['result']['Results'];
//        $this->dataForView['Excellence'] = $result['result']['Excellence'];

        /**
         * 获取所有的排名, 自己的排名
         */
        $this->_makeRankingReady();
        /**
         * 获取所有的排名, 自己的排名 end
         */

        /**
         * 计算历史数据
         */
        $this->dataForView['History'] = History::GetAll($this->userObject);

        /**
         * 计算Credits
         */
        $this->dataForView['Credits'] = Credit::QueryByUserAndYearPeriod($this->userObject,env('YEAR',2017));

        /**
         * 以上是基础数据, 以下为页面中的特定数据
         */

        // 处理 Leader Board 的表格: Leader board 只有5个位置
        $this->dataForView['hasPlatinumRanking'] = false;
        $role = RoleFactory::GetRole($this->userObject->position, $this->userObject);
        $this->dataForView['leaderBoardStatusData'] = Ranking::getLeaderBoardData($this->userObject, $this->dataForView['Rankings']);
        if($role->hasPlatinumRanking){
            $this->dataForView['hasPlatinumRanking'] = true;
            $this->dataForView['leaderBoardPlatinumData'] = Ranking::getLeaderBoardData($this->userObject, $this->dataForView['RankingsPlatinum']);
        }
        // 处理 Leader Board 的表格 结束

    }

    /**
     * 获取所有的排名, 自己的排名
     * @return void
     */
    private function _makeRankingReady(){
        // Get the latest ranking date
        $thisPeriod = $this->_getThisPeriod($this->userObject);

        $role = RoleFactory::GetRole($this->userObject->position, $this->userObject);

        // 获取了所有的 Rankings: Get all rankings
        $rankings = Ranking::Query($this->userObject, $thisPeriod, Ranking::AWARD_STATUS);
        $rankingsPlatinum = Ranking::Query($this->userObject, $thisPeriod, Ranking::AWARD_PLATINUM);

        $this->dataForView['Rankings'] = $rankings;
        $this->dataForView['RankingsPlatinum'] = $rankingsPlatinum;

        $statusRanking = '';
        foreach ($rankings as $ranking) {
            if($ranking['member_id'] == $this->userObject->getEmployeeCode()){
                $statusRanking = $ranking['rank'];
                $platinumRanking = $ranking['rank_platinum'];
                break;
            }
        }
        /**
         * Calculate the region and nationally ranking
         */
        $this->dataForView['statusRanking'] = $statusRanking;

        $this->dataForView['platinumRanking'] = '';
        if($role->hasPlatinumRanking){
            //$rankingRegionally = Ranking::countRegionalRankingLessThan($this->userObject,$thisPeriod,$statusRanking);
            //$this->dataForView['rankingRegionally'] = $rankingRegionally ? $rankingRegionally+1 : 1;
            $this->dataForView['platinumRanking'] = $platinumRanking;
        }

    }

    /**
     * 综合各种情况, 获取当前登陆用户的 position
     * Handle user's position; Handle multiple roles situation
     * @return string | null
     */
    public function setUserCurrentRoleAndTableName(){
        /**
         * 先尝试获取是否用户提交了 asRole, 这个值应该是职务的缩写
         * @var string $asRole : Must be the position's abbr
         */
        $this->asRole = $this->request->param('asRole');
        if(empty($this->asRole)){
            $selectedRole = session_get('selected_role');
            if($selectedRole){
                // 用户以前选定的角色, 应该持续使用
                $this->asRole = $selectedRole;
            }
        }else{
            session_set('selected_role',$this->asRole);
        }

        if($this->asRole){
            $this->userObject->position = $this->asRole;
        }

        /**
         * 从现在起, user的 position 就是和提交的 role 请求一样了
         */

        // Find all user's roles
        $this->userPositions = $this->userObject->getPositions();
        $this->userHasMultipleRoles = count($this->userPositions) > 1;

        // By default, give current user a default position
        $this->targetTableName = DataSource::nissan_get_table_name_from_abbr(
            $this->userObject->position
        );

        // Set to the view
        $this->dataForView['userHasMultipleRoles'] = $this->userHasMultipleRoles;
        $this->dataForView['asRole'] = $this->asRole;
        $this->dataForView['currentRoleText'] = DataSource::getRoleNameByAbbr($this->userObject->position);
        $this->dataForView['targetDatabaseTableName'] = $this->targetTableName;
        $this->dataForView['userPositions'] = $this->userPositions;


        /**
         *  userPositions array is in the below structure
            array(2) {
                ["nissan_salesconsultants"]=>
                    string(16) "Sales Consultant"
                ["nissan_salesmanagers"]=>
                    string(13) "Sales Manager"
            }
         *
         */
    }


    /**
     * Generate the "this period" data
     * @param User $user
     * @param string $role
     * @return Carbon|null|string
     */
    protected function _getThisPeriod(User $user, $role = null){
        $thisPeriod = date('Y-m').'-01';
        $thisPeriod = Carbon::createFromFormat('Y-m-d',$thisPeriod);

        if($period = Ranking::QueryThisPeriod($user, $role)){
            $thisPeriod = $period;
        }
        return $thisPeriod;
    }
